"""Generate the kernel's conservative object-size limits from local presets."""
import argparse
import hashlib
import json
from pathlib import Path


def generate(manifest_path, output):
    manifest_path = Path(manifest_path).resolve()
    root = manifest_path.parent
    manifest = json.loads(manifest_path.read_text(encoding='utf-8-sig'))
    if manifest.get('schema_version') != 1:
        raise ValueError('Unsupported preset manifest')
    bounds = {}
    for entry in manifest['presets']:
        path = (root / entry['file']).resolve()
        if not path.is_relative_to(root):
            raise ValueError('Preset path escapes its directory')
        raw = path.read_bytes()
        expected_hash = entry.get('preset_sha256') or entry.get('sha256')
        if not expected_hash or hashlib.sha256(raw).hexdigest() != expected_hash:
            raise ValueError(f'Preset hash mismatch: {entry["id"]}')
        preset = json.loads(raw)
        size = preset['size']
        if preset['id'] != entry['id'] or size != entry['size'] or not 0 < size <= 4096:
            raise ValueError(f'Invalid object size: {entry["id"]}')
        if (entry.get('architecture') != 'x64' or not entry.get('auto_select', True)
                or entry.get('nt_major') != 10 or entry.get('nt_minor') != 0):
            continue
        for build in entry['build_numbers']:
            # Existing driver imports PsGetProcessStartKey (Windows 10 1703+).
            if not isinstance(build, int) or build < 15063:
                continue
            bounds[build] = min(bounds.get(build, size), size)
    if not bounds:
        raise ValueError('No compatible native x64 Windows build limits')
    source = ['#pragma once', '',
              '// Generated by kernel_control_panel/tools/generate_eprocess_bounds.py.',
              '// Factual sizeof(_EPROCESS) from bundled Vergilius x64 presets.',
              '// Shared build numbers use the smallest declared object size.',
              '// Unknown builds must never read a guessed object extent.',
              'namespace helper { namespace process_object {',
              '    inline ULONG KnownProcessObjectSize(ULONG build)',
              '    {', '        switch (build)', '        {']
    for build, size in sorted(bounds.items()):
        source.append(f'        case {build}UL: return 0x{size:X}UL;')
    source.extend(['        default: return 0;', '        }', '    }', '} }', ''])
    destination = Path(output)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text('\n'.join(source), encoding='utf-8')
    return bounds


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    panel = Path(__file__).resolve().parents[1]
    parser.add_argument('--manifest', type=Path, default=panel / 'presets' / 'eprocess' / 'manifest.json')
    parser.add_argument('--output', type=Path, default=panel.parent / 'helper' / 'process_object_layouts.h')
    args = parser.parse_args()
    print(json.dumps(generate(args.manifest, args.output), indent=2))
